    // 1. Método para cargar los datos en la JTable
private void listarProductos() {
    com.huellitas.dao.ProductoDAO dao = new com.huellitas.dao.ProductoDAO();
    java.util.List<com.huellitas.model.Producto> lista = dao.listar();
    
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) productosTbl.getModel();
    
    // Limpiamos las filas anteriores
    modelo.setRowCount(0);
    
    // Si la tabla no tiene las columnas configuradas aún, se las ponemos
    if (modelo.getColumnCount() == 0) {
        modelo.addColumn("ID");
        modelo.addColumn("Código");
        modelo.addColumn("Nombre");
        modelo.addColumn("Stock");
        modelo.addColumn("Stock Mín.");
        modelo.addColumn("Precio");
    }
    
    // Llenamos la tabla fila por fila
    for (com.huellitas.model.Producto p : lista) {
        Object[] fila = new Object[6];
        fila[0] = p.getIdProducto();
        fila[1] = p.getCodigo();
        fila[2] = p.getNombre();
        fila[3] = p.getStock();
        fila[4] = p.getStockMinimo();
        fila[5] = p.getPrecio();
        modelo.addRow(fila);
    }
}

// 2. Método para limpiar las cajas de texto tras guardar
