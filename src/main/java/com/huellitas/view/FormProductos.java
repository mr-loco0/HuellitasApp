    private void guardarBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarBtnActionPerformed
        // TODO add your handling code here:                                           
    try {
        // Leemos lo que el usuario escribió en las cajas de texto
        String codigo = codigoTF.getText().trim();
        String nombre = nombreTF.getText().trim();
        
        if (codigo.isEmpty() || nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor completa el código y el nombre.");
            return;
        }

        int stock = Integer.parseInt(stockTF.getText().trim());
        int stockMinimo = Integer.parseInt(stockMinimoTF.getText().trim());
        double precio = Double.parseDouble(precioTF.getText().trim());

        // Creamos el objeto Producto y llamamos al DAO
        com.huellitas.model.Producto p = new com.huellitas.model.Producto(codigo, nombre, stock, stockMinimo, precio);
        com.huellitas.dao.ProductoDAO dao = new com.huellitas.dao.ProductoDAO();

        if (dao.registrar(p)) {
            javax.swing.JOptionPane.showMessageDialog(this, "¡Producto guardado exitosamente!");
            limpiarCampos();
            listarProductos(); // Refresca la tabla automáticamente
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al guardar el producto en la base de datos.");
        }
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Asegúrate de ingresar números válidos en Stock, Stock Mínimo y Precio.");
    }
    }//GEN-LAST:event_guardarBtnActionPerformed

